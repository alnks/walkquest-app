package app.walkquest.data.settings

/**
 * Режим темы приложения (решение владельца 2026-10-17, история 7.16):
 * ручной выбор поверх системной. Персистится в SettingsRepository по имени
 * enum'а (как WalkMode). Default — SYSTEM (следуем настройкам телефона).
 * Живёт в data/settings (не в ui/theme): хранилище не знает про Compose.
 */
enum class ThemeMode {
    /** Системная (по умолчанию): тёмная/светлая следует настройке телефона. */
    SYSTEM,

    /** Принудительно светлая, независимо от системной. */
    LIGHT,

    /** Принудительно тёмная, независимо от системной. */
    DARK,
}

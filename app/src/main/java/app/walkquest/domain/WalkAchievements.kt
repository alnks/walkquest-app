package app.walkquest.domain

/**
 * Порт достижений прогулки (история 2.8, FR-8): финальный экран показывает
 * «полученные Ачивки», но условия достижений — содержание epic-achievements-quests
 * (FR-15/FR-16, каталог из 40). Контракт фиксируем сейчас — интеграция потом
 * подключит реализацию к этому интерфейсу без переделки экрана.
 *
 * Чистый Kotlin (AD-10): вход — агрегаты прогулки (дистанция, чистое время),
 * выход — человекочитаемые названия новых достижений (пусто — ни одного).
 */
fun interface WalkAchievements {

    /**
     * Новые достижения за завершённую прогулку. Реализация по умолчанию до
     * epic-achievements — `{ emptyList() }` (AppContainer): экран показывает
     * сводку без блока ачивок.
     */
    fun forWalk(distanceMeters: Double, activeMillis: Long): List<String>
}

package app.walkquest.domain

/**
 * Похвала на финальном экране (история 2.8, FR-8): тон — спокойный, приятный
 * (Aesthetic and Tone PRD), без крикливых суперлативов. Строка выбирается
 * детерминированно по дистанции прогулки — одинаковая прогулка даёт одинаковую
 * похвалу. Чистый Kotlin (AD-10) — JVM-тестируемо; UI только рендерит.
 */
object WalkPraise {

    /** Похвала по дистанции прогулки, метры. */
    fun forDistance(distanceMeters: Double): String = when {
        distanceMeters >= 20_000.0 ->
            "Большой путь. Город заметил вас сегодня."
        distanceMeters >= 10_000.0 ->
            "Отличная прогулка — целый десяток километров."
        distanceMeters >= 5_000.0 ->
            "Хорошая прогулка. Так держать."
        distanceMeters >= 1_000.0 ->
            "Неплохая прогулка — километр есть."
        distanceMeters >= 50.0 ->
            "Прогулка состоялась. Это главное."
        else ->
            "Коротко, но вы вышли. Уже победа."
    }

    /** Подпись «про завтра» — постоянная строка экрана (FR-8). */
    const val TOMORROW_NOTE = "Завтра город расступится чуть больше. До встречи на маршруте."
}
